// The functional checks: every feature exercised in headless Chromium; prints PASS / FAIL per check and the console errors.
//   PLAYWRIGHT=/path/to/node_modules/playwright node tools/check.cjs
const { chromium, URL } = require('./pw.cjs')
;(async () => {
  const b = await chromium.launch()
  const p = await b.newPage({ viewport: { width: 1680, height: 1050 } })
  const errs = []
  p.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errs.push(m.type() + ': ' + m.text()) })
  p.on('pageerror', (e) => errs.push('pageerror: ' + e.message))
  await p.goto(URL + '?theme=light')
  await p.waitForTimeout(500)
  const ev = (f, a) => p.evaluate(f, a)
  const rowsShown = () => ev(() => [...document.querySelectorAll('#lv-layer .lv-row .lv-ln')].map((x) => +x.textContent).filter(Boolean))
  const ok = (name, cond, extra = '') => console.log((cond ? 'PASS ' : 'FAIL ') + name + (extra ? '  ' + extra : ''))
  ok('fonts loaded', await ev(() => document.fonts.check('12px "IBM Plex Mono"') && document.fonts.check('13px "IBM Plex Sans"')))
  // last line: G
  await p.focus('#lv'); await p.keyboard.press('Shift+G'); await p.waitForTimeout(150)
  let shown = await rowsShown(); ok('G shows the last line of dump 1 (18523)', shown.includes(18523), 'max ' + Math.max(...shown))
  await p.keyboard.press('g'); await p.waitForTimeout(100)
  shown = await rowsShown(); ok('g back to line 1', shown.includes(1))
  // scroll by wheel to the end
  await ev(() => { const lv = document.querySelector('#lv'); lv.scrollTop = lv.scrollHeight }); await p.waitForTimeout(150)
  shown = await rowsShown(); ok('scrolled to the bottom shows 18523', shown.includes(18523))
  // v toggles raw
  await p.keyboard.press('v'); await p.waitForTimeout(100)
  ok('v: Raw', await ev(() => window.__app.S.mode === 'raw' && document.querySelector('#m-raw').getAttribute('aria-checked') === 'true'))
  ok('raw has one row per line', await ev(() => window.__app.VIEW().rows.length === window.__app.D().n))
  await p.keyboard.press('v'); await p.waitForTimeout(100)
  ok('v: Formatted', await ev(() => window.__app.S.mode === 'fmt'))
  ok('formatted has fewer rows (folds, banners)', await ev(() => window.__app.VIEW().rows.length), '')
  console.log('   formatted rows', await ev(() => window.__app.VIEW().rows.length), 'of', await ev(() => window.__app.D().n), 'lines')
  // ] [ landmarks
  await p.keyboard.press('g'); await p.keyboard.press(']'); await p.waitForTimeout(100)
  const l1 = await ev(() => window.__app.S.sel)
  await p.keyboard.press(']'); const l2 = await ev(() => window.__app.S.sel)
  await p.keyboard.press('['); const l3 = await ev(() => window.__app.S.sel)
  ok('] and [ step landmarks', l1 > 0 && l2 > l1 && l3 === l1, `${l1} ${l2} ${l3}`)
  ok('landmark counter', (await p.textContent('#lm-count')).startsWith('1 /'), await p.textContent('#lm-count'))
  // r R runs
  await p.keyboard.press('g'); await p.keyboard.press('r'); const r1 = await ev(() => window.__app.S.sel); await p.keyboard.press('r'); const r2 = await ev(() => window.__app.S.sel); await p.keyboard.press('Shift+R'); const r3 = await ev(() => window.__app.S.sel); ok('r / R: runs', r1 === 1347 && r2 === 4263 && r3 === 1347, `${r1} ${r2} ${r3}`)
  // / focuses search; regex
  await p.keyboard.press('/'); ok('/ focuses search', await ev(() => document.activeElement.id === 'q'))
  await p.click('#q-re'); await p.focus('#q')
  await p.keyboard.type('Best:: (Access|Join)')
  await p.waitForTimeout(300)
  const hits = await ev(() => window.__app.S.hits.length); ok('regex search hits', hits === 78, hits + ' (expected 20 AccessPath + 58 JoinMethod)')
  await p.keyboard.press('Enter'); const h1 = await ev(() => window.__app.S.hitCur)
  await p.keyboard.press('Enter'); const h2 = await ev(() => window.__app.S.hitCur)
  await p.keyboard.press('Shift+Enter'); const h3 = await ev(() => window.__app.S.hitCur)
  ok('Enter / Shift+Enter step hits', h2 > h1 && h3 === h1, `${h1} ${h2} ${h3}`)
  ok('marks drawn', await ev(() => document.querySelectorAll('#lv-layer mark').length > 0))
  ok('outline hit badges', await ev(() => document.querySelectorAll('#lbody .ol-hits').length > 2), await ev(() => [...document.querySelectorAll('#lbody .ol-hits')].map((x) => x.textContent).join(',')))
  await p.keyboard.press('Escape')
  await p.keyboard.press('F3'); const h4 = await ev(() => window.__app.S.hitCur); ok('F3 next hit', h4 === h2, h4)
  await p.fill('#q', '(unclosed'); await p.waitForTimeout(300); ok('bad regex says invalid', (await p.textContent('#q-count')) === 'invalid')
  await p.click('#q-re'); await p.waitForTimeout(300); ok('literal search of "(unclosed" has 0 hits', await ev(() => window.__app.S.hits.length === 0 && !window.__app.S.qbad))
  await p.fill('#q', ''); await p.waitForTimeout(300)
  // folds: click a fold row, z, Z
  await ev(() => window.__app.select(165, 'top')); await p.waitForTimeout(100)
  await ev(() => window.__app.select(400)); await p.waitForTimeout(100)
  ok('selecting a line inside a closed fold opens it', await ev(() => window.__app.VIEW().rows[window.__app.rowOf(400)].t === 'line'))
  await ev(() => { const a = window.__app; a.S.foldOv.clear(); a.rebuild(); a.updateAll() })
  await ev(() => window.__app.goNode(window.__app.D().nodes.find((n) => n.kind === 'params-default').id)); await p.waitForTimeout(100)
  const foldBtn = await p.$('#lv-layer .lv-fold'); ok('a fold handle is on screen', !!foldBtn)
  const before = await ev(() => window.__app.VIEW().rows.length)
  await foldBtn.click(); await p.waitForTimeout(100)
  const after = await ev(() => window.__app.VIEW().rows.length); ok('click opens the fold', after > before, `${before} -> ${after}`)
  await p.focus('#lv'); await p.keyboard.press('z'); await p.waitForTimeout(100)
  ok('z closes it again', await ev(() => window.__app.VIEW().rows.length) === before)
  await p.keyboard.press('Shift+Z'); await p.waitForTimeout(100)
  const all = await ev(() => window.__app.VIEW().rows.length); ok('Z unfolds all', all > after, all)
  ok('button says Default folds', (await p.textContent('#fold-all')) === 'Default folds')
  await p.keyboard.press('Shift+Z'); ok('Z back to defaults', await ev(() => window.__app.VIEW().rows.length) === before)
  // bookmarks
  await ev(() => window.__app.select(1868)); await p.focus('#lv'); await p.keyboard.press('b'); await p.waitForTimeout(100)
  ok('b bookmarks the line', await ev(() => window.__app.S.bms.has(1868)))
  ok('diamond on the line', await ev(() => !!document.querySelector('#lv-layer .lv-bm')))
  await p.click('[data-ltab="bookmarks"]'); await p.waitForTimeout(100)
  ok('bookmark listed', await ev(() => document.querySelectorAll('#lbody .bms li').length === 1))
  await p.fill('#lbody input[data-note="1868"]', 'check the join order'); await p.waitForTimeout(100)
  ok('note kept', await ev(() => window.__app.S.bms.get(1868) === 'check the join order'))
  await p.click('[data-ltab="outline"]')
  // outline click scrolls
  await p.click('#lbody .ol-row[data-node] >> text=Result'); await p.waitForTimeout(150)
  ok('outline click goes to Result', await ev(() => window.__app.topLine() >= 15729 && window.__app.topLine() <= 15731), await ev(() => window.__app.topLine()))
  ok('outline marks Result', await ev(() => document.querySelector('#lbody .ol-row.on')?.textContent.includes('Result') || document.querySelector('#lbody .ol-row.on')?.textContent.includes('Statement dump')))
  // crumbs are links
  await ev(() => window.__app.select(1937)); await p.waitForTimeout(100)
  const crumbs = await ev(() => [...document.querySelectorAll('#crumbs button')].map((b) => b.textContent))
  ok('path', crumbs.length >= 6, crumbs.join(' › '))
  await p.click('#crumbs button:nth-of-type(4)'); await p.waitForTimeout(100)
  ok('a crumb jumps', await ev(() => window.__app.S.sel), await ev(() => window.__app.S.sel))
  // line map click
  const box = await (await p.$('#strip')).boundingBox()
  await p.mouse.click(box.x + 8, box.y + box.height * 0.9); await p.waitForTimeout(150)
  ok('line map click goes near 90 %', await ev(() => { const t = window.__app.topLine(); return t > 16000 && t < 17500 }), await ev(() => window.__app.topLine()))
  // plan toggle
  await ev(() => window.__app.goNode(window.__app.D().nodes.find((n) => n.kind === 'plan').id)); await p.waitForTimeout(150)
  ok('plan rows', await ev(() => document.querySelectorAll('#lv-layer .lv-tbl').length > 10))
  await p.click('[data-plan="text"]'); await p.waitForTimeout(150)
  ok('plan as text', await ev(() => document.querySelectorAll('#lv-layer .lv-tbl').length === 0 && [...document.querySelectorAll('#lv-layer .lv-tx')].some((x) => x.textContent.includes('| Id  | Operation'))))
  // theme button cycles
  const t0 = await p.textContent('#theme-label'); await p.click('#theme'); const t1 = await p.textContent('#theme-label'); await p.click('#theme'); const t2 = await p.textContent('#theme-label')
  ok('theme cycles', t0 !== t1 && t1 !== t2, `${t0} ${t1} ${t2} data-theme=${await ev(() => document.documentElement.dataset.theme)}`)
  // second dump via outline, d key
  await p.click('#lbody [data-dump="1"]'); await p.waitForTimeout(200)
  ok('dump 2 opens', await ev(() => window.__app.S.dump === 1 && window.__app.topLine() === 18524), await ev(() => window.__app.topLine()))
  await p.focus('#lv'); await p.keyboard.press('Shift+G'); await p.waitForTimeout(100)
  shown = await rowsShown(); ok('last line of the file 27780', shown.includes(27780))
  await p.keyboard.press('d'); ok('d: next dump', await ev(() => window.__app.S.dump === 0))
  // glossary card
  await ev(() => window.__app.select(1436, 'top')); await p.waitForTimeout(150)
  const gl = await p.$('#lv-layer .gl[data-t="CLUF"]')
  if (gl) { await gl.hover(); await p.waitForTimeout(100); ok('glossary card', await ev(() => !document.querySelector('#card').hidden && document.querySelector('#card').textContent.includes('clustering factor')), await p.textContent('#card')) } else ok('glossary term CLUF on screen', false)
  // guide with no entry
  await ev(() => window.__app.select(842)); await p.waitForTimeout(100)
  ok('a section without an entry says so', (await p.textContent('#rbody')).includes('No guide text for this kind of section'))
  console.log(errs.join('\n') || 'no console errors')
  await b.close()
})()
