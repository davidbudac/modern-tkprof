// Drives the mock-up the way the owner will and checks that the interactions work.
//   PLAYWRIGHT=…/node_modules/playwright [CHROMIUM=…] node tools/check.cjs
const { chromium, BASE } = require('./pw.cjs')
let pass = 0, fail = 0
const ok = (name, cond, extra = '') => { if (cond) pass++; else { fail++; console.log('FAIL', name, extra) } }
;(async () => {
  const browser = await chromium.launch(process.env.CHROMIUM ? { executablePath: process.env.CHROMIUM } : {})
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  const errs = []
  page.on('pageerror', (e) => errs.push(String(e)))
  const open = async (q) => { await page.goto(BASE + '?' + q); await page.waitForSelector('body[data-ready="1"]'); await page.waitForTimeout(250) }
  const T = (sel) => page.locator(sel).first().innerText()

  // ---- the error stack file, variant A
  await open('file=errorstack&variant=a&theme=light')
  ok('errorstack: outline has the sections', (await page.locator('.ol-row').count()) > 15)
  ok('errorstack: call stack reading', (await T('#rd-centre')).includes('86trfcf9m9n9f') && (await T('#rd-centre')).includes('MTK_DIAG_INNER'))
  ok('errorstack: the dump\'s own frames are folded', /10\s+frames of the dump itself/.test(await T('#rd-centre')) && !(await T('#rd-centre')).includes('dbgdParseCmd()'))
  await page.click('[data-own-toggle]')
  ok('errorstack: own frames open', (await T('#rd-centre')).includes('dbkedDefDump'))
  const one = await page.locator('#oneline').innerText()
  ok('errorstack: one-line stack', one.startsWith('kkyase()+15725<-kksExecuteCommand()+10100<-') && one.split('<-').length === 34, one.slice(0, 80))
  await page.click('input[data-own]')
  ok('errorstack: one-line stack with the dump\'s own frames', (await page.locator('#oneline').innerText()).split('<-').length === 44)
  await page.click('#m-text')
  ok('text: the viewer is shown', await page.locator('#lv-box').isVisible())
  await page.waitForTimeout(300); await page.evaluate(() => __app.reveal(180, 'top')); await page.waitForTimeout(200)
  const folds0 = await page.locator('.lv-row.x-fold').count()
  ok('text: closed folds are on screen', folds0 > 0)
  const rows0 = await page.evaluate(() => __app.VIEW().rows.length)
  await page.locator('.lv-row.x-fold .lv-fold').first().click()
  const rows1 = await page.evaluate(() => __app.VIEW().rows.length)
  ok('text: a fold opens', rows1 > rows0, `${rows0} -> ${rows1}`)
  await page.click('#fold-all')
  const rowsAll = await page.evaluate(() => __app.VIEW().rows.length)
  ok('text: unfold all', rowsAll > rows1 && rowsAll === 36651, String(rowsAll))
  await page.click('#fold-all')
  ok('text: default folds back', (await page.evaluate(() => __app.VIEW().rows.length)) < 36651)
  await page.fill('#q', 'SQL*Net')
  await page.waitForTimeout(300)
  const cnt = await T('#q-count')
  ok('search: count shown', /0 \/ \d+/.test(cnt), cnt)
  await page.press('#q', 'Enter')
  ok('search: Enter selects the first hit', /^1 \/ \d+/.test(await T('#q-count')))
  ok('search: hit is marked in the text', (await page.locator('.lv-tx mark').count()) > 0)
  await page.fill('#q', '')
  await page.waitForTimeout(250)
  await page.locator('.ol-row', { hasText: 'Process State Dump' }).first().click()
  ok('outline: a node can be selected', (await T('#crumbs')).includes('Process State Dump'))
  const first = await page.locator('.ol-row.on .ol-label').first().innerText()
  ok('outline: selection mark', first.includes('Process State Dump'), first)
  await page.locator('.ol-row', { hasText: 'Pinned Buffer History' }).first().locator('.ol-x').click()
  ok('outline: a node opens', (await page.locator('.ol-row', { hasText: 'Buffer header 1' }).count()) > 0)
  await page.locator('.ol-row', { hasText: 'Pinned Buffer History' }).first().locator('.ol-x').click()
  ok('outline: a node closes', (await page.locator('.ol-row', { hasText: 'Buffer header 1' }).count()) === 0)

  // ---- the process reading
  await open('file=process&variant=a&theme=light')
  const pr = await T('#rd-centre')
  ok('process: who', pr.includes('22.14058') && pr.includes('sqlplus@ol9-19-dg1') && pr.includes('mtk_diag_errorstack_l2'))
  ok('process: waits', pr.includes('Not in wait'))
  ok('process: holds by type', pr.includes('LIBRARY OBJECT LOCK') && pr.includes('LIBRARY OBJECT PIN') && pr.includes('enqueue'))
  ok('process: statement', pr.includes('mtk_diag_outer'))

  // ---- the heap file
  await open('file=heap&variant=a&theme=light')
  const hr = await T('#rd-centre')
  ok('heap: the check line', hr.includes('Chunks sum to 4,707,160 bytes: matches the dump\'s Total heap size'), hr.slice(0, 400))
  ok('heap: the free and permanent checks', hr.includes('49,560') && hr.includes('392,464'))
  ok('heap: the tree has the sub-heaps', hr.includes('koh-kghu call') && hr.includes('top call heap'))
  const firstRow = await page.locator('.heaptbl tbody tr').first().innerText()
  await page.click('th.sortable button[data-sort="chunks"]')
  ok('heap: sort by chunks (descending first)', (await page.locator('th.sortable[aria-sort="descending"]').count()) === 1)
  await page.click('th.sortable button[data-sort="chunks"]')
  ok('heap: sort toggles', (await page.locator('th.sortable[aria-sort="ascending"]').count()) === 1)
  const asc = await page.locator('.heaptbl tbody tr td.num:nth-child(3)').allInnerTexts()
  const nums = asc.map((s) => +s.replace(/,/g, ''))
  ok('heap: rows are in order', nums.every((v, i) => i === 0 || nums[i - 1] <= v), nums.slice(0, 6).join())
  await page.click('[data-tab="type"]')
  ok('heap: by type', (await page.locator('.heaptbl tbody tr').count()) === 4 && (await T('.heaptbl')).includes('freeable'))
  await page.click('[data-tab="subs"]')
  ok('heap: sub-heaps', (await page.locator('.heaptbl tbody tr').count()) === 5)
  await page.click('[data-tab="comment"]')
  await page.locator('.heaptbl tbody tr', { hasText: 'koh-kghu call' }).first().click()
  ok('heap: a row selects its chunks', (await page.locator('.chunkbar').count()) === 1)
  const sel0 = await page.evaluate(() => __app.S.sel)
  await page.click('[data-chunk="1"]')
  ok('heap: next chunk', (await page.evaluate(() => __app.S.chunk.i)) === 1)
  await page.click('[data-chunk-show]')
  await page.waitForTimeout(400)
  ok('heap: show in text switches the centre', await page.locator('#lv-box').isVisible())
  ok('heap: the chunk lines are marked', (await page.locator('.lv-row.lv-hl').count()) > 0)
  await page.click('#m-read')
  await page.locator('.tn', { hasText: 'diag pga' }).first().click()
  ok('heap: move to another heap by the tree', (await T('.rd-head h3')).includes('diag pga'))
  ok('heap: the chunk selection is dropped', (await page.locator('.chunkbar').count()) === 0)
  await page.locator('.ol-row', { hasText: 'Heap dump 2 of 3' }).first().click()
  ok('heap: a node without a reading says so', (await T('#lv-box')) !== '' && (await page.locator('#m-read').isDisabled()))
  // all heap checks, through the page's own data
  const checks = await page.evaluate(() => { const hs = DIAG.heap.readings.heaps; return { n: hs.length, ok: hs.filter((h) => h.check.chunks && h.check.chunks.ok && (!h.check.free || h.check.free.ok) && (!h.check.perm || h.check.perm.ok)).length } })
  ok('heap: every check matches', checks.n === 80 && checks.ok === 80, JSON.stringify(checks))

  // ---- variant B
  await open('file=heap&variant=b&theme=light')
  ok('B: the reading is in the right panel', (await T('#rbody')).includes('Chunks sum to'))
  ok('B: the centre is the text', await page.locator('#lv-box').isVisible() && !(await page.locator('#m-read').isVisible()))
  const w0 = await page.evaluate(() => document.querySelector('.side-r').getBoundingClientRect().width)
  const box = await page.locator('#resizer').boundingBox()
  await page.mouse.move(box.x + 4, box.y + 200); await page.mouse.down(); await page.mouse.move(box.x - 120, box.y + 200, { steps: 4 }); await page.mouse.up()
  const w1 = await page.evaluate(() => document.querySelector('.side-r').getBoundingClientRect().width)
  ok('B: the panel resizes', w1 > w0 + 80, `${w0} -> ${w1}`)
  await page.click('#var-a')
  ok('A/B toggle', (await page.getAttribute('#app', 'data-variant')) === 'a' && (await T('#rbody')).includes('A heap dump'))

  // ---- the theme
  const t0 = await page.evaluate(() => document.documentElement.getAttribute('data-theme'))
  await page.click('#theme')
  const t1 = await page.evaluate(() => document.documentElement.getAttribute('data-theme'))
  await page.click('#theme')
  const t2 = await page.evaluate(() => document.documentElement.getAttribute('data-theme'))
  ok('theme: cycles', t0 === 'light' && t1 === 'dark' && t2 === null, `${t0} ${t1} ${t2}`)

  // ---- the system state
  await open('file=sysstate&variant=a&theme=light')
  const sr = await T('#rd-centre')
  ok('sysstate: blocker tree', sr.includes('52.41898') && sr.includes('45.12004') && sr.includes('255.62769') && sr.includes('final blocker'))
  const all = await page.locator('.proctbl tbody tr').count()
  ok('sysstate: 85 processes', all === 85, String(all))
  await page.click('input[data-hide-idle]')
  const some = await page.locator('.proctbl tbody tr').count()
  ok('sysstate: hide idle background', some === 85 - 73, String(some))
  await page.locator('.proctbl tbody tr[data-proc="61"]').click()
  ok('sysstate: a process opens its reading', (await T('#rd-centre')).includes('255.62769') && (await T('#rd-centre')).includes('Wait history'))
  await page.click('#m-text')
  await page.waitForTimeout(300); await page.evaluate(() => __app.reveal(2330, 'top')); await page.waitForTimeout(200)
  ok('sysstate: text has gaps said as such', (await page.locator('.x-gap').count()) > 0)
  await page.locator('.ol-row', { hasText: 'System state' }).first().click()
  ok('sysstate: back to the system state reading', (await T('#rd-centre')).includes('Blocker tree'))

  // ---- the hang analysis
  await open('file=hang&variant=a&theme=light')
  const hg = await T('#rd-centre')
  ok('hang: chains', hg.includes('Chain 1') && hg.includes('Chain 2') && hg.includes('61.26319'))

  // ---- URL parameters
  await open('file=heap&variant=b&theme=dark&heap=h30')
  ok('url: file, variant, theme, heap', (await page.getAttribute('#app', 'data-variant')) === 'b' && (await page.evaluate(() => document.documentElement.getAttribute('data-theme'))) === 'dark' && (await T('.rd-head h3')).includes('session heap'))

  ok('no script errors', errs.length === 0, errs.join(' | '))
  console.log(`${pass} passed, ${fail} failed`)
  await browser.close()
  process.exit(fail ? 1 : 0)
})()
