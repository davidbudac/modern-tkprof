interface Profile { total: number; buckets: number; size: number; calls: number[]; waits: number[] }

/**
 * GET a JSON answer of the session for the document `epoch`; `path` null fetches nothing. Debounced, and aborted when the
 * path or the document changes (a live session's next snapshot answers the same path anew, through the same client). While
 * another answer loads, the previous one stays (`data`, with `path` saying which request it answers: see `currentOf`).
 */
function useJSON<T>(client: ApiClient, path: string | null, epoch: unknown, delay = 120): JSONView<T> {
  const [st, setSt] = useState<JSONState<T>>({ path: null })
  useEffect(() => {
    if (!path) return
    const ac = new AbortController()
    const settle = (r: JSONResult<T>) => setSt((cur) => jsonSettle(cur, path, r, ac.signal.aborted, epoch))
    const t = setTimeout(() => {
      client.fetch(path, { signal: ac.signal })
        .then(async (r) => { if (!r.ok) throw await responseError(r, path.split('?')[0]); return r.json() as Promise<T> })
        .then((data) => settle({ data }), (e: unknown) => settle({ error: e instanceof Error ? e.message : String(e) }))
    }, delay)
    return () => { clearTimeout(t); ac.abort() }
  }, [client, path, epoch, delay])
  return jsonView(st, path, epoch)
}

/** The size of an element (ResizeObserver). */
function useSize<T extends HTMLElement>(): [React.RefObject<T | null>, { w: number; h: number }] {
  const ref = useRef<T>(null)
  const [size, setSize] = useState({ w: 0, h: 0 })
  useLayoutEffect(() => {
    const el = ref.current
    if (!el) return
    const ro = new ResizeObserver(() => setSize({ w: el.clientWidth, h: el.clientHeight }))
    ro.observe(el)
    setSize({ w: el.clientWidth, h: el.clientHeight })
    return () => ro.disconnect()
  }, [])
  return [ref, size]
}

/** Re-renders when the color scheme changes (the canvas reads resolved colors). */
function useSchemeKey(): string {
  const theme = useStore((s) => s.theme)
  const [dark, setDark] = useState(() => matchMedia('(prefers-color-scheme: dark)').matches)
  useEffect(() => {
    const mq = matchMedia('(prefers-color-scheme: dark)')
    const on = () => setDark(mq.matches)
    mq.addEventListener('change', on)
    const mo = new MutationObserver(on)
    mo.observe(document.documentElement, { attributes: true, attributeFilter: ['data-theme', 'class', 'style'] })
    return () => { mq.removeEventListener('change', on); mo.disconnect() }
  }, [])
  return `${theme}:${dark}:${document.documentElement.dataset.theme ?? ''}`
}

export function CutView({ doc }: { doc: TraceDoc }) {
  const client = useClient()
  const actions = useActions()
  const ws = useWorkspace()
  const tab = useCurrentTab()
  const win = useStore((s) => s.window)
  const contexts = useStore((s) => scopeOf(s).contexts)
  const selStmt = useStore((s) => s.selection.stmt)
  const [mode, setMode] = useState<Mode>('window')
  const [stmt, setStmt] = useState<ID | null>(null)
  const [edges, setEdges] = useState<Edges>('calls')
  const [binds, setBinds] = useState<Binds | null>(null)
  const [plans, setPlans] = useState(true)
  const [prov, setProv] = useState(true)
  const [sel, setSel] = useState<number | null>(null)
  const [busy, setBusy] = useState<string | null>(null)
  const [msg, setMsg] = useState<{ ok: boolean; text: string; path?: string } | null>(null)

  // the statements to pick from: every one with calls, by elapsed; the pick is one of them (a pick of an earlier live
  // snapshot, or a selection elsewhere of a statement without calls, falls back to the longest)
  const choices = useMemo(() => stmtChoices(doc), [doc])
  const pick = pickOf(choices, stmt, selStmt)
  const noStmt = mode === 'statement' && pick === null

  const query = useMemo(() => {
    const q = new URLSearchParams()
    if (win) { q.set('from', String(Math.floor(win.startTim))); q.set('to', String(Math.ceil(win.endTim))) }
    if (contexts) q.set('contexts', contexts.size ? [...contexts].sort((a, b) => a - b).join(',') : '-')
    if (mode === 'statement' && pick !== null) q.set('stmt', String(pick))
    if (edges !== 'calls') q.set('edges', edges)
    if (binds) q.set('binds', binds)
    if (!plans) q.set('plans', '0')
    if (!prov) q.set('prov', '0')
    return q.toString()
  }, [win, contexts, mode, pick, edges, binds, plans, prov])

  const planPath = noStmt ? null : `/api/cut?${query}`
  const plan = useJSON<CutPlan>(client, planPath, doc)
  // p is what the map draws: the current plan, or the previous one while the next is planned (dimmed, "Planning…");
  // current is the plan of this very query: only it authorises an export or a check, and only its size decides the check
  const p = plan.data
  const current = currentOf(plan, planPath)
  const pending = !!p && !current
  const autoCheck = autoCheckOf(current)
  // a check asked for is of this query on this document: a live session's next snapshot is asked again (a big check is
  // not re-run on every snapshot); a small one is re-run by itself
  const [checkWanted, setCheckWanted] = useState<{ query: string; doc: TraceDoc } | null>(null)
  const check = useJSON<CutCheck>(client, checkPath(current, query, checkWanted?.doc === doc ? checkWanted.query : null), doc, 300)
  const files = doc.file.files ?? []
  const profilePaths = useMemo(() => files.map((_, i) => `/api/lines/profile?file=${i}&buckets=600`).join('|'), [files])
  const [profiles, setProfiles] = useState<Profile[]>([])
  useEffect(() => {
    const ac = new AbortController()
    Promise.all(profilePaths.split('|').map((u) => client.fetch(u, { signal: ac.signal }).then((r) => (r.ok ? (r.json() as Promise<Profile>) : null))))
      .then((ps) => setProfiles(ps.map((x) => x ?? { total: 0, buckets: 0, size: 1, calls: [], waits: [] })), () => {})
    return () => ac.abort()
  }, [client, profilePaths, doc]) // a live snapshot's files have grown

  useEffect(() => { setSel(null) }, [query])
  const pieces = p?.pieces ?? []
  const selIdx = sel ?? defaultPiece(pieces)
  const multi = files.length > 1
  const title = multi && !win && mode === 'window' ? `Join ${files.length} files into a new trace` : 'Cut a new trace'
  const fileName = `${traceStem(doc, tab)}-cut.trc`

  const fetchFile = async () => {
    const r = await client.fetch(`/api/cut/file?${query}`)
    if (!r.ok) throw await responseError(r, 'cut')
    if (!r.body) throw new Error('cut: empty answer')
    return r.body
  }
  // the new file opens with this tab's bind handling (never as a live session)
  const openTab = (path: string) => ws.openOrShow({ paths: [path], options: { binds: tab?.set.options.binds ?? 'keep', salt: tab?.set.options.salt } })
  const run = (what: string, fn: () => Promise<{ text: string; path?: string } | null>) => {
    setBusy(what)
    setMsg(null)
    fn().then((m) => m && setMsg({ ok: true, ...m }), (e: unknown) => setMsg({ ok: false, text: e instanceof Error ? e.message : String(e) })).finally(() => setBusy(null))
  }
  const save = () => run('save', async () => {
    const path = await saveAs(safeFileName(fileName), fetchFile, [{ name: 'Oracle trace', extensions: ['trc'] }], 'Save the new trace')
    return path ? { text: `Saved ${path}`, path: inApp ? path : undefined } : null
  })
  // a name of its own in the cuts folder (<stem>-cut-<yyyymmdd-hhmmss>.trc): an earlier cut's tab keeps reading its own file
  const openNew = () => run('open', async () => {
    const path = await writeCut(traceStem(doc, tab), await fetchFile())
    openTab(path)
    return { text: `Opened ${path} in a new tab`, path }
  })

  return (
    <section className="cut" aria-label="Cut a new trace">
      <header className="cut-head">
        <div>
          <h2>{title}</h2>
          <div className="from">
            from <span className="mono">{multi ? `${files.length} files` : files[0]?.name ?? doc.file.path}</span> · {fmtInt(files.reduce((a, f) => a + f.lines, 0))} lines · {fmtBytes(files.reduce((a, f) => a + f.size, 0))}
          </div>
        </div>
        <div className="grow" />
        <span>
          <span className="lbl">Keep</span>
          <span className="seg" role="group" aria-label="Keep">
            <button aria-pressed={mode === 'window'} onClick={() => setMode('window')} title="whole top-level calls in the time window (or the whole trace) and the sessions or files selected">Calls in the window</button>
            <button aria-pressed={mode === 'statement'} onClick={() => setMode('statement')} title="one statement's calls with their recursive work; its callers are left out">One statement</button>
          </span>
        </span>
        {mode === 'statement' && <StmtPicker choices={choices} pick={pick} onPick={setStmt} />}
        {inApp && <button onClick={openNew} disabled={!canExport(current, busy !== null)} title="writes the new file to the app cache folder and opens it in a new tab">{busy === 'open' ? 'Opening…' : 'Open as new tab'}</button>}
        <button className="primary" onClick={save} disabled={!canExport(current, busy !== null)} title={pending ? 'planning the cut of the new selection' : current?.lines === 0 ? 'the selection keeps nothing: there is no file to save' : undefined}>{busy === 'save' ? 'Saving…' : 'Save as…'}</button>
      </header>
      <TimeStrip doc={doc} client={client} contexts={contexts} plan={current} mode={mode} onWindow={(w) => actions.setWindow(w)} />
      <div className={pending ? 'cut-stage pending' : 'cut-stage'} aria-busy={plan.loading}>
        <Legend mode={mode} multi={multi} />
        {pending && <span className="cut-badge" role="status">Planning…</span>}
        {noStmt ? <p className="cut-empty">No statement of this trace has calls: there is nothing to cut by statement.</p>
          : plan.error ? <p className="cut-msg bad" role="alert">{plan.error}</p>
          : !p ? <p className="cut-empty">{plan.loading ? 'Planning the cut…' : ''}</p>
          : p.lines === 0 ? (
            <p className="cut-empty">
              Nothing to keep: no call of the selection lies in the window and the sessions selected.{' '}
              {win && <button className="quiet" onClick={() => actions.setWindow(null)}>Use the whole trace</button>}
            </p>
          )
          : <CutMap doc={doc} plan={p} profiles={profiles} sel={selIdx} onSel={setSel} mode={mode} />}
        {msg && (
          <p className={msg.ok ? 'cut-msg' : 'cut-msg bad'} role={msg.ok ? 'status' : 'alert'}>
            {msg.text} {msg.ok && msg.path && busy === null && !msg.text.startsWith('Opened') && <button className="quiet" onClick={() => openTab(msg.path!)}>Open it in a new tab</button>}
          </p>
        )}
      </div>
      <aside className={pending ? 'cut-side pending' : 'cut-side'}>
        {p && p.lines > 0 && (
          <>
            <PieceCard doc={doc} plan={p} piece={pieces[selIdx]} mode={mode} onShow={(f, l) => actions.openLinesAt(f, l, { keepSelection: true })} />
            <FileCard doc={doc} plan={p} pending={pending} check={check} autoCheck={autoCheck} onCheck={() => setCheckWanted({ query, doc })} />
            <SelectionCard doc={doc} plan={p} mode={mode} win={win} contexts={contexts} />
          </>
        )}
        <section>
          <h3>Options</h3>
          <div className="cut-card cut-opts">
            <span>Edges</span>
            <span className="seg" role="group" aria-label="Edges">
              <button aria-pressed={edges === 'calls'} onClick={() => setEdges('calls')} title="keep whole calls (with everything under them)">Whole calls</button>
              <button aria-pressed={edges === 'executions'} onClick={() => setEdges('executions')} title="widen to whole executions: every FETCH of a kept EXEC and the other way round">Whole executions</button>
            </span>
            <span>Bind values</span>
            <span className="seg" role="group" aria-label="Bind values">
              {(['keep', 'mask', 'none'] as const).map((b) => {
                const allowed = !p || p.bindsAllowed.includes(b)
                return (
                  <button key={b} aria-pressed={(binds ?? p?.binds) === b} disabled={!allowed} onClick={() => setBinds(b)}
                    title={!allowed ? 'this tab was opened with bind values redacted or left out' : b === 'mask' ? 'each value replaced by a token of its type, length and a hash' : b === 'none' ? 'leave the BINDS blocks out' : 'as traced'}>
                    {b === 'keep' ? 'Keep' : b === 'mask' ? 'Mask' : 'None'}
                  </button>
                )
              })}
            </span>
            <span className="d">Mask to send the file to someone: equal values keep equal tokens.</span>
            <label htmlFor="cut-plans">Plans from outside the cut</label>
            <input id="cut-plans" type="checkbox" checked={plans} onChange={(e) => setPlans(e.target.checked)} />
            <label htmlFor="cut-prov">Provenance lines in the header</label>
            <input id="cut-prov" type="checkbox" checked={prov} onChange={(e) => setProv(e.target.checked)} />
          </div>
        </section>
      </aside>
    </section>
  )
}

/** The piece shown first: a borrowed cursor when there is one (what the view is about), else the first kept block. */
function defaultPiece(pieces: readonly CutPiece[]): number {
  const i = pieces.findIndex((x) => x.kind === 'before' && x.title?.startsWith('Cursor'))
  if (i >= 0) return i
  const k = pieces.findIndex((x) => x.kind === 'kept')
  return k >= 0 ? k : 0
}

function Legend({ mode, multi }: { mode: Mode; multi: boolean }) {
  const keys: (Label | 'G')[] = mode === 'statement' ? ['K', 'B', 'A', 'G', 'C', '.'] : multi ? ['K', 'E', 'B', 'A', 'G', '.'] : ['K', 'E', 'B', 'A', 'G', '.']
  return (
    <div className="cut-legend">
      {keys.map((k) => {
        const L = LABEL[k]
        const c = `var(${L.v})`
        const style = L.hatch ? { background: `repeating-linear-gradient(135deg, ${c} 0 2px, color-mix(in oklch, ${c} 35%, transparent) 2px 4px)` }
          : k === 'G' ? { background: `color-mix(in oklch, ${c} 18%, transparent)`, outline: `1px dashed ${c}`, outlineOffset: '-1px' }
          : k === '.' ? { background: `color-mix(in oklch, ${c} 16%, transparent)` } : { background: c }
        return <span key={k}><i style={style} />{L.name}</span>
      })}
    </div>
  )
}

