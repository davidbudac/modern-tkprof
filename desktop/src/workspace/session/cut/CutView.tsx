function TimeStrip({ doc, client, contexts, plan, mode, onWindow }: {
  doc: TraceDoc; client: ApiClient; contexts: Set<ID> | null; plan?: CutPlan; mode: Mode; onWindow: (w: { startTim: number; endTim: number } | null) => void
}) {
  const [ref, { w }] = useSize<HTMLDivElement>()
  const win = useStore((s) => s.window)
  const t0 = doc.span.firstTim
  const t1 = Math.max(doc.span.lastTim, t0 + 1)
  const bucket = Math.max(1, Math.ceil((t1 - t0) / 320))
  const ctx = contexts ? `&contexts=${contexts.size ? [...contexts].sort((a, b) => a - b).join(',') : '-'}` : ''
  const tl = useJSON<{ n: number; firstTim: number; cpu: number[]; events: { event: number; us: number[] }[] }>(client, `/api/timeline?bucket=${bucket}&idle=0${ctx}`, doc, 0)
  const [drag, setDrag] = useState<[number, number] | null>(null)
  const L0 = 120
  const R = Math.max(L0 + 10, w - 4)
  const H = 46
  const top = 18
  const x = (t: number) => L0 + ((t - t0) / (t1 - t0)) * (R - L0)
  const tOf = (px: number) => t0 + ((Math.min(R, Math.max(L0, px)) - L0) / (R - L0)) * (t1 - t0)
  const area = useMemo(() => {
    const d = tl.data
    if (!d) return ''
    const busy = new Float64Array(d.n)
    for (let i = 0; i < d.n; i++) busy[i] = d.cpu[i] ?? 0
    for (const e of d.events) for (let i = 0; i < d.n; i++) busy[i] += e.us[i] ?? 0
    const bw = (x(t0 + bucket) - x(t0))
    let s = `M${x(d.firstTim)},${top + H}`
    for (let i = 0; i < d.n; i++) {
      const h = (Math.min(1.2, busy[i] / bucket) / 1.2) * (H - 4)
      const xx = x(d.firstTim + i * bucket)
      s += ` L${xx},${top + H - h} L${xx + bw},${top + H - h}`
    }
    return s + ` L${x(d.firstTim + d.n * bucket)},${top + H} Z`
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [tl.data, w])
  const ticks = useMemo(() => {
    const span = t1 - t0
    const steps = [1e3, 2e3, 5e3, 1e4, 2e4, 5e4, 1e5, 2e5, 5e5, 1e6, 2e6, 5e6, 1e7, 3e7, 6e7, 3e8, 6e8, 1.8e9, 3.6e9]
    const step = steps.find((s) => span / s <= Math.max(2, (R - L0) / 110)) ?? 3.6e9
    const out: number[] = []
    for (let t = Math.ceil(t0 / step) * step; t < t1; t += step) out.push(t)
    return out
  }, [t0, t1, R])
  const down = (e: React.PointerEvent<SVGSVGElement>) => {
    const bx = e.currentTarget.getBoundingClientRect().left
    e.currentTarget.setPointerCapture(e.pointerId)
    setDrag([e.clientX - bx, e.clientX - bx])
  }
  const move = (e: React.PointerEvent<SVGSVGElement>) => { if (drag) setDrag([drag[0], e.clientX - e.currentTarget.getBoundingClientRect().left]) }
  const up = () => {
    if (!drag) return
    const [a, b] = drag
    setDrag(null)
    if (Math.abs(b - a) < 3) return
    onWindow({ startTim: tOf(Math.min(a, b)), endTim: tOf(Math.max(a, b)) })
  }
  const kept = plan && plan.calls > 0 ? [plan.keptFrom, plan.keptTo] : null
  const keptC = 'var(--cut-kept)'
  return (
    <div className="cut-strip"><div ref={ref}>
      <svg width={w} height={top + H + 22} onPointerDown={down} onPointerMove={move} onPointerUp={up} role="img"
        aria-label="Busy time over the trace; drag to choose a time window">
        <defs>
          <pattern id="cut-hatch" width="6" height="6" patternUnits="userSpaceOnUse" patternTransform="rotate(45)">
            <rect width="2.5" height="6" fill={keptC} fillOpacity="0.5" />
          </pattern>
        </defs>
        <text x={0} y={top + 12} className="tb" style={{ font: '600 12px var(--font-ui)', fill: 'var(--ink)' }}>Time</text>
        <text x={0} y={top + 26} style={{ font: '11px var(--font-ui)', fill: 'var(--ink-3)' }}>{win ? 'drag: another' : 'drag: a window'}</text>
        {win && <text x={0} y={top + 40} style={{ font: '11px var(--font-ui)', fill: 'var(--ink-2)', cursor: 'pointer', textDecoration: 'underline' }}
          onPointerDown={(e) => e.stopPropagation()} onClick={() => onWindow(null)}>whole trace</text>}
        <rect x={L0} y={top} width={R - L0} height={H} fill="var(--surface-sunken)" />
        <path d={area} fill="var(--ink-3)" fillOpacity={0.45} />
        {kept && <rect x={x(kept[0])} y={top - 2} width={Math.max(2, x(kept[1]) - x(kept[0]))} height={H + 4} fill={keptC} fillOpacity={mode === 'statement' ? 0.5 : 0.14} />}
        {kept && win && kept[1] > win.endTim && <rect x={x(win.endTim)} y={top - 2} width={x(kept[1]) - x(win.endTim)} height={H + 4} fill="url(#cut-hatch)" />}
        {kept && win && kept[0] < win.startTim && <rect x={x(kept[0])} y={top - 2} width={x(win.startTim) - x(kept[0])} height={H + 4} fill="url(#cut-hatch)" />}
        {win && <rect x={x(win.startTim)} y={top - 2} width={Math.max(1, x(win.endTim) - x(win.startTim))} height={H + 4} fill="none" stroke={keptC} strokeWidth={1.5} strokeDasharray="4 3" />}
        {win && kept && (kept[1] > win.endTim || kept[0] < win.startTim) && (
          <text x={x(Math.max(kept[1], win.endTim)) + 6} y={top + H / 2 + 4} style={{ font: '11px var(--font-ui)', fill: 'var(--ink-2)', paintOrder: 'stroke', stroke: 'var(--surface)', strokeWidth: 3 }}
            textAnchor={x(kept[1]) > R - 220 ? 'end' : 'start'} dx={x(kept[1]) > R - 220 ? -12 - (x(kept[1]) - x(win.endTim)) : 0}>
            {`+${fmtDur(Math.max(0, kept[1] - win.endTim) + Math.max(0, win.startTim - kept[0]))} to keep calls whole (hatched)`}
          </text>
        )}
        {drag && <rect x={Math.min(...drag)} y={top - 2} width={Math.abs(drag[1] - drag[0])} height={H + 4} fill={keptC} fillOpacity={0.18} stroke={keptC} />}
        {ticks.map((t) => (
          <g key={t}>
            <line x1={x(t)} x2={x(t)} y1={top + H} y2={top + H + 4} stroke="var(--ink-3)" />
            <text x={x(t)} y={top + H + 16} textAnchor="middle" style={{ font: '11px var(--font-ui)', fill: 'var(--ink-3)', fontVariantNumeric: 'tabular-nums' }}>
              {doc.wallOf(t) ? fmtWall(doc.wallOf(t), doc.tzOffsetMin) : fmtDur(t - t0)}
            </text>
          </g>
        ))}
      </svg>
    </div></div>
  )
}

