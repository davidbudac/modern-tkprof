function PieceCard({ doc, plan, piece, mode, onShow }: { doc: TraceDoc; plan: CutPlan; piece?: CutPiece; mode: Mode; onShow: (file: number, line: number) => void }) {
  if (!piece) return null
  const L = pieceLabel(piece)
  const v = `var(${LABEL[L].v})`
  const [title] = pieceText(plan, piece)
  const kind = L === 'K' ? 'Kept' : LABEL[L].name
  const where = piece.from
    ? `source ${plan.files.length > 1 ? (plan.files.find((f) => f.idx === piece.file)?.name ?? '') + ' ' : ''}${srcRange(piece)} → new file ${piece.o0 === piece.o1 ? `line ${fmtInt(piece.o0)}` : `lines ${fmtInt(piece.o0)}–${fmtInt(piece.o1)}`}`
    : `new file ${piece.o0 === piece.o1 ? `line ${fmtInt(piece.o0)}` : `lines ${fmtInt(piece.o0)}–${fmtInt(piece.o1)}`}`
  let why: ReactNode = piece.reason
  if (piece.kind === 'kept' && !piece.title) {
    const sql = mode === 'statement' ? plan.statements[0] : undefined
    why = mode === 'statement'
      ? <>The calls of {sql ? <code>{doc.statements[sql.id]?.sqlId || `#${sql.id}`}</code> : 'the statement'} with their binds, plan lines and recursive work. The lines of its callers around them are left out.</>
      : <>Top-level calls overlapping the window (or all of them), each with what is rolled up under it: its waits, binds and recursive SQL.{piece.edge ? <> {fmtInt(piece.edge)} call and wait lines lie outside the window: they finish a call that started inside it, so its numbers stay true.</> : null}</>
    if ((piece.runs ?? 1) > 1) why = <>{why} {fmtInt(piece.runs ?? 1)} runs of consecutive lines with nothing inserted between them.</>
  }
  // line numbers: the source's for one run of lines, else the new file's
  const srcNums = !!piece.from && !piece.lines?.length && (piece.kind !== 'kept' || (piece.runs ?? 1) === 1)
  const first = srcNums ? piece.from! : piece.o0
  const last = srcNums ? piece.to ?? piece.from! : piece.o1
  const head = piece.head ?? []
  const rows: ReactNode[] = head.map((t, j) => <div key={`h${j}`}><span className="ln">{fmtInt(first + j)}</span><span className="tx">{t || ' '}</span></div>)
  if (piece.tail?.length) {
    const skipped = piece.n - head.length - piece.tail.length
    if (skipped > 0) rows.push(<div key="ell" className="ell">⋯ {fmtInt(skipped)} more lines</div>)
    piece.tail.forEach((t, j) => rows.push(<div key={`t${j}`}><span className="ln">{fmtInt(last - piece.tail!.length + 1 + j)}</span><span className="tx">{t || ' '}</span></div>))
  }
  return (
    <section>
      <h3>Piece</h3>
      <div className="cut-card">
        <span className="cut-chip" style={{ background: `color-mix(in oklch, ${v} 16%, transparent)` }}><i style={{ background: v }} />{kind}</span>
        <div className="cut-piece-title">{title}</div>
        <div className="cut-piece-where">{where}</div>
        <div className="cut-piece-why">{why}</div>
        <div className="cut-raw">{rows}</div>
        {piece.from && <div className="cut-piece-actions"><button className="quiet" onClick={() => onShow(piece.file, piece.lines?.[0] ?? piece.from!)}>Show in Trace</button></div>}
      </div>
    </section>
  )
}

